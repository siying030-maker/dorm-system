def build_tabs(role, is_main):

    tab_names = []

    # ==================================================
    # 舍監 / 行政
    # ==================================================

    if role in ["舍監", "行政"]:

        tab_names += [
            "連三天不假外宿",
            "每日缺席名單"
        ]

    # ==================================================
    # 行政功能
    # ==================================================

    if role == "行政":

        tab_names += [
            "上學期門禁",
            "下學期門禁",
            "整潔比賽(檢視)"
        ]

    # ==================================================
    # 樓長功能
    # ==================================================

    if role == "樓長":

        tab_names += [
            "每日缺席名單"
        ]

        # 主樓長才有整潔比賽
        if is_main:

            tab_names += [
                "整潔比賽"
            ]

    # ==================================================
    # 去重
    # ==================================================

    tab_names = list(dict.fromkeys(tab_names))

    return tab_names